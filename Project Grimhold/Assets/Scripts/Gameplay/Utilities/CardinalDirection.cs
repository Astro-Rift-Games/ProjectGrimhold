/// <summary>
/// Representa las 8 orientaciones cardinales para la navegación e indicación espacial (Doc 14).
/// </summary>
public enum CardinalDirection : byte
{
    None = 0,
    North = 1,
    NorthEast = 2,
    East = 3,
    SouthEast = 4,
    South = 5,
    SouthWest = 6,
    West = 7,
    NorthWest = 8
}
