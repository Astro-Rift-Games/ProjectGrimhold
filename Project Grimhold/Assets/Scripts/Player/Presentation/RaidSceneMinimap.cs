using UnityEngine;

/// <summary>
/// Declares the generated <see cref="MinimapLayout"/> of the Raid scene that contains it. Each Raid map
/// owns exactly one instance, so the local HUD shows the map that is actually loaded instead of a layout
/// baked into the shared HUD prefab. The source Tilemap root is read only by the editor generator.
/// </summary>
[DisallowMultipleComponent]
public sealed class RaidSceneMinimap : MonoBehaviour
{
    [SerializeField]
    [Tooltip("Generated layout of this scene. Regenerated by MinimapLayoutGenerator from the source Tilemaps.")]
    private MinimapLayout _layout;

    [SerializeField]
    [Tooltip("Root containing exactly one Floor, Walls and Obstacles Tilemap on the same Grid (editor generation only).")]
    private GameObject _sourceTilemapRoot;

    public MinimapLayout Layout => _layout;

    public GameObject SourceTilemapRoot => _sourceTilemapRoot;

    /// <summary>
    /// Resolves the layout declared by the loaded Raid scene. Called once per HUD bind, never per frame.
    /// Fails instead of falling back so a map without a declared layout never shows another map.
    /// </summary>
    public static bool TryResolveLoaded(out MinimapLayout layout, out string error)
    {
        layout = null;
        RaidSceneMinimap[] candidates =
            FindObjectsByType<RaidSceneMinimap>(FindObjectsInactive.Exclude, FindObjectsSortMode.None);
        if (candidates.Length != 1)
        {
            error = $"Exactly one active {nameof(RaidSceneMinimap)} is required in the loaded Raid scene; found {candidates.Length}.";
            return false;
        }

        if (candidates[0]._layout == null)
        {
            error = $"{nameof(RaidSceneMinimap)} in scene '{candidates[0].gameObject.scene.name}' has no MinimapLayout.";
            return false;
        }

        layout = candidates[0]._layout;
        error = null;
        return true;
    }

#if UNITY_EDITOR
    /// <summary>Editor composition entry point used by map builders.</summary>
    public void EditorConfigure(MinimapLayout layout, GameObject sourceTilemapRoot)
    {
        _layout = layout;
        _sourceTilemapRoot = sourceTilemapRoot;
    }
#endif
}
